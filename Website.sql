  CREATE OR REPLACE EDITIONABLE TRIGGER "UEB_AUTO_STATUS" 
AFTER INSERT OR UPDATE OF LoanStatus
ON UEB_BORROWING_RECORDS
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        IF :NEW.LoanStatus <> 'Borrowed' THEN
            RAISE_APPLICATION_ERROR(-20001,
                'New record must be Borrowed');
        END IF;

        UPDATE UEB_EQUIPMENT
        SET Status = 'Borrowed'
        WHERE EquipmentID = :NEW.EquipmentID
          AND Status = 'Available'
          AND Condition = 'Good';

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20002,
                'Equipment is not available');
        END IF;

    ELSIF UPDATING THEN
        IF :OLD.LoanStatus = 'Borrowed'
           AND :NEW.LoanStatus = 'Returned' THEN

            IF :NEW.ReturnCondition IS NULL THEN
                RAISE_APPLICATION_ERROR(-20003,
                    'Return condition is required');
            END IF;

            UPDATE UEB_EQUIPMENT
            SET Condition = :NEW.ReturnCondition,
                Status = CASE
                    WHEN :NEW.ReturnCondition = 'Good'
                    THEN 'Available'
                    ELSE 'Maintenance'
                END
            WHERE EquipmentID = :NEW.EquipmentID;

        ELSIF :OLD.LoanStatus = 'Borrowed'
          AND :NEW.LoanStatus = 'Missing' THEN

            UPDATE UEB_EQUIPMENT
            SET Condition = 'Missing',
                Status = 'Maintenance'
            WHERE EquipmentID = :NEW.EquipmentID;

        ELSIF :OLD.LoanStatus <> :NEW.LoanStatus THEN
            RAISE_APPLICATION_ERROR(-20004,
                'Invalid loan status change');
        END IF;
    END IF;
END;

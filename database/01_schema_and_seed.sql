-- University Equipment Borrowing & Return Management System
-- Oracle APEX SQL Workshop. Run as the workspace parsing schema.
-- Four requested relational tables; no APEX App Builder required.

CREATE TABLE UEB_CATEGORIES (
    CATEGORY_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CATEGORY_NAME VARCHAR2(100) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR2(500)
);

CREATE TABLE UEB_EQUIPMENT (
    EQUIPMENT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CATEGORY_ID NUMBER NOT NULL,
    EQUIPMENT_NAME VARCHAR2(150) NOT NULL,
    MODEL VARCHAR2(100),
    SERIAL_NUMBER VARCHAR2(100) NOT NULL UNIQUE,
    PURCHASE_DATE DATE,
    CONDITION VARCHAR2(30) DEFAULT 'GOOD' NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'AVAILABLE' NOT NULL,
    CONSTRAINT FK_UEB_EQUIP_CATEGORY FOREIGN KEY (CATEGORY_ID)
        REFERENCES UEB_CATEGORIES(CATEGORY_ID),
    CONSTRAINT CK_UEB_EQUIP_CONDITION CHECK (CONDITION IN ('GOOD','FAIR','DAMAGED','NEEDS_MAINTENANCE')),
    CONSTRAINT CK_UEB_EQUIP_STATUS CHECK (STATUS IN ('AVAILABLE','BORROWED','MAINTENANCE','RETIRED'))
);

CREATE TABLE UEB_BORROWERS (
    BORROWER_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(150) NOT NULL,
    EMAIL VARCHAR2(255) NOT NULL UNIQUE,
    PHONE VARCHAR2(30),
    BORROWER_TYPE VARCHAR2(30) NOT NULL,
    DEPARTMENT VARCHAR2(100),
    ROLE VARCHAR2(30) DEFAULT 'BORROWER' NOT NULL,
    CONSTRAINT CK_UEB_BORROWER_TYPE CHECK (BORROWER_TYPE IN ('STUDENT','FACULTY','STAFF')),
    CONSTRAINT CK_UEB_BORROWER_ROLE CHECK (ROLE IN ('ADMIN','STAFF','VIEWER','BORROWER'))
);

CREATE TABLE UEB_BORROWING_RECORDS (
    BORROW_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    EQUIPMENT_ID NUMBER NOT NULL,
    BORROWER_ID NUMBER NOT NULL,
    ISSUE_DATE DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    DUE_DATE DATE NOT NULL,
    RETURN_DATE DATE,
    RETURN_CONDITION VARCHAR2(30),
    LOAN_STATUS VARCHAR2(30) DEFAULT 'ACTIVE' NOT NULL,
    REMARKS VARCHAR2(1000),
    CONSTRAINT FK_UEB_LOAN_EQUIPMENT FOREIGN KEY (EQUIPMENT_ID)
        REFERENCES UEB_EQUIPMENT(EQUIPMENT_ID),
    CONSTRAINT FK_UEB_LOAN_BORROWER FOREIGN KEY (BORROWER_ID)
        REFERENCES UEB_BORROWERS(BORROWER_ID),
    CONSTRAINT CK_UEB_LOAN_DATES CHECK (DUE_DATE >= ISSUE_DATE),
    CONSTRAINT CK_UEB_RETURN_DATE CHECK (RETURN_DATE IS NULL OR RETURN_DATE >= ISSUE_DATE),
    CONSTRAINT CK_UEB_RETURN_CONDITION CHECK (RETURN_CONDITION IS NULL OR RETURN_CONDITION IN ('GOOD','FAIR','DAMAGED','NEEDS_MAINTENANCE')),
    CONSTRAINT CK_UEB_LOAN_STATUS CHECK (LOAN_STATUS IN ('ACTIVE','RETURNED','OVERDUE'))
);

-- Enforce one active (not-yet-returned) loan per equipment, even under concurrent requests.
CREATE UNIQUE INDEX UEB_ONE_ACTIVE_LOAN_UX
ON UEB_BORROWING_RECORDS (
    CASE WHEN RETURN_DATE IS NULL AND LOAN_STATUS = 'ACTIVE' THEN EQUIPMENT_ID END
);

CREATE INDEX UEB_LOAN_DUE_IX ON UEB_BORROWING_RECORDS(DUE_DATE, RETURN_DATE);
CREATE INDEX UEB_EQUIP_CATEGORY_IX ON UEB_EQUIPMENT(CATEGORY_ID);

-- Compound trigger avoids ORA-04091 (mutating-table) when recalculating status.
CREATE OR REPLACE TRIGGER UEB_LOAN_EQUIPMENT_STATUS_TRG
FOR INSERT OR UPDATE OR DELETE ON UEB_BORROWING_RECORDS
COMPOUND TRIGGER
    TYPE id_list_t IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
    g_ids id_list_t;
    g_count PLS_INTEGER := 0;

    PROCEDURE remember_id(p_id NUMBER) IS
    BEGIN
        IF p_id IS NOT NULL THEN
            g_count := g_count + 1;
            g_ids(g_count) := p_id;
        END IF;
    END;

    AFTER EACH ROW IS
    BEGIN
        IF INSERTING THEN
            remember_id(:NEW.EQUIPMENT_ID);
        ELSIF DELETING THEN
            remember_id(:OLD.EQUIPMENT_ID);
        ELSE
            remember_id(:NEW.EQUIPMENT_ID);
            IF :OLD.EQUIPMENT_ID <> :NEW.EQUIPMENT_ID THEN
                remember_id(:OLD.EQUIPMENT_ID);
            END IF;
        END IF;
    END AFTER EACH ROW;

    AFTER STATEMENT IS
        v_active_count NUMBER;
        v_id NUMBER;
    BEGIN
        FOR i IN 1..g_count LOOP
            v_id := g_ids(i);
            SELECT COUNT(*) INTO v_active_count
            FROM UEB_BORROWING_RECORDS
            WHERE EQUIPMENT_ID = v_id
              AND RETURN_DATE IS NULL
              AND LOAN_STATUS = 'ACTIVE';

            UPDATE UEB_EQUIPMENT e
            SET STATUS = CASE
                WHEN e.CONDITION IN ('DAMAGED','NEEDS_MAINTENANCE') THEN 'MAINTENANCE'
                WHEN v_active_count > 0 THEN 'BORROWED'
                ELSE 'AVAILABLE'
            END
            WHERE e.EQUIPMENT_ID = v_id;
        END LOOP;
    END AFTER STATEMENT;
END UEB_LOAN_EQUIPMENT_STATUS_TRG;
/

-- When a returned item is reported damaged, set equipment condition and status.
CREATE OR REPLACE TRIGGER UEB_RETURN_CONDITION_TRG
AFTER UPDATE OF RETURN_DATE, RETURN_CONDITION ON UEB_BORROWING_RECORDS
FOR EACH ROW
WHEN (NEW.RETURN_DATE IS NOT NULL)
BEGIN
    IF :NEW.RETURN_CONDITION IN ('DAMAGED','NEEDS_MAINTENANCE') THEN
        UPDATE UEB_EQUIPMENT
        SET CONDITION = :NEW.RETURN_CONDITION, STATUS = 'MAINTENANCE'
        WHERE EQUIPMENT_ID = :NEW.EQUIPMENT_ID;
    ELSIF :NEW.RETURN_CONDITION IS NOT NULL THEN
        UPDATE UEB_EQUIPMENT
        SET CONDITION = :NEW.RETURN_CONDITION
        WHERE EQUIPMENT_ID = :NEW.EQUIPMENT_ID;
    END IF;
END;
/

